#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../.."
website/playground-engine/build.sh
node website/playground-engine/tests/form-model.test.cjs
node website/playground-engine/tests/form-dom.test.cjs
PLAYGROUND_LOCALE=zh node website/playground-engine/tests/form-dom.test.cjs
node website/playground-engine/tests/site.test.cjs
# The rendered contrast gate is required, never silently skipped. The protected
# build installs the pinned Playwright/axe-core packages first; install them
# here too so the gate also runs when an older caller workflow is in effect.
if ! node -e "require.resolve('playwright',{paths:['website/playground-engine']});require.resolve('axe-core',{paths:['website/playground-engine']})" 2>/dev/null; then
  npm --prefix website/playground-engine ci --ignore-scripts
  website/playground-engine/node_modules/.bin/playwright install chromium
fi
node website/playground-engine/a11y-smoke.cjs
node --check docs/hugo/static/js/command-copy.js
python3 website/tests/test_language_routes.py
python3 website/localize-links.py docs --check
# llms.txt and llms-full.txt are generated by build-site.sh, not static files.
# The published tree must carry them and they must match the generator, or the
# site silently loses its AI-discovery files on the next publication.
git ls-files --error-unmatch docs/llms.txt docs/llms-full.txt >/dev/null
python3 website/generate-llms.py --check docs
python3 website/tests/check_llms.py docs
# Executable documentation checks run in the global test gate.
# This job verifies the browser engine and generated site.
website/playground-engine/verify-hugo.sh
git diff --exit-code -- docs/playground docs/hugo/static/playground docs/css docs/hugo/static/css
test -z "$(git ls-files --others --exclude-standard -- docs/playground docs/hugo/static/playground docs/css docs/hugo/static/css)"
