export function t(value) {
  const text = String(value);
  const lang = typeof document === 'undefined' ? 'en' : document.documentElement?.lang || document.querySelector('html')?.getAttribute('lang') || 'en';
  if (!lang.toLowerCase().startsWith('zh')) return text;
  if (Object.hasOwn(messages, text)) return messages[text];
  let match;
  if ((match = /^(\d+) lines$/.exec(text))) return `${match[1]} 行`;
  if ((match = /^Value (\d+)$/.exec(text))) return `值 ${match[1]}`;
  if ((match = /^Remove principal (\d+)$/.exec(text))) return `移除身份 ${match[1]}`;
  if ((match = /^Remove attribute (\d+)$/.exec(text))) return `移除属性 ${match[1]}`;
  if ((match = /^Remove value (\d+) from attribute (\d+)$/.exec(text))) return `移除属性 ${match[2]} 的值 ${match[1]}`;
  return text.replace(/^Line (\d+) · /, '第 $1 行 · ').replace(/^Unable to load the Speedle engine\. /, '无法加载 Speedle 引擎：');
}
